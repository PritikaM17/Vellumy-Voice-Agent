CREATE TABLE specialities (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                TEXT NOT NULL UNIQUE,
    plain_description   TEXT NOT NULL,
    for_gender          TEXT NOT NULL DEFAULT 'any'
                        CHECK (for_gender IN ('any', 'female', 'male'))
);

CREATE TABLE symptoms (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snomed_id TEXT NOT NULL,
    name TEXT NOT NULL UNIQUE,
    embedding REAL[]
);

CREATE TABLE symptom_rules (
    symptom_id INTEGER PRIMARY KEY REFERENCES symptoms(id),
    speciality_id INTEGER NOT NULL REFERENCES specialities(id),
    vote_share FLOAT
);

CREATE TABLE red_flags (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phrase TEXT NOT NULL UNIQUE,
    response_message TEXT NOT NULL
);

CREATE TABLE patients (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT UNIQUE,
    date_of_birth DATE NOT NULL,
    gender TEXT NOT NULL
            CHECK (gender IN ('female', 'male', 'other'))
);

CREATE TABLE doctors (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    speciality_id INTEGER NOT NULL REFERENCES specialities(id),
    fee INTEGER
);

CREATE TABLE doctor_slots (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id INTEGER NOT NULL REFERENCES doctors(id),
    starts_at TIMESTAMPTZ NOT NULL,
    UNIQUE(doctor_id, starts_at)
);

CREATE TABLE symptom_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES patients(id),
    raw_text TEXT NOT NULL,
    phrase TEXT NOT NULL,
    matched_symptom_id INTEGER REFERENCES symptoms(id),
    similarity FLOAT,
    suggested_speciality_id INTEGER REFERENCES specialities(id),
    reason TEXT NOT NULL
            CHECK(reason IN ('rule', 'child', 'gender', 'mixed', 'no_match', 'emergency')),
    is_emergency BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE appointments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES patients(id),
    slot_id INTEGER NOT NULL REFERENCES doctor_slots(id),
    symptom_log_id INTEGER REFERENCES symptom_logs(id),
    status TEXT NOT NULL DEFAULT 'booked'
            CHECK(status IN ('booked', 'cancelled', 'completed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE tool_calls (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_name TEXT NOT NULL,
    args_json JSONB,
    result_json JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_doctors_speciality_id ON doctors (speciality_id);

CREATE INDEX idx_symptom_logs_patients ON symptom_logs(patient_id, created_at);

CREATE INDEX idx_appointments_patients ON appointments(patient_id);

CREATE UNIQUE INDEX idx_appointments_active_booking ON appointments(slot_id)
WHERE status = 'booked';

CREATE VIEW appointment_details AS 
SELECT 
    a.id AS appointment_id,
    a.patient_id,
    p.name AS patient,
    d.name AS doctor,
    sp.name AS speciality,
    s.starts_at,
    a.status
FROM appointments a
JOIN patients p ON p.id = a.patient_id
JOIN doctor_slots s ON s.id = a.slot_id
JOIN doctors d ON d.id = s.doctor_id
JOIN specialities sp ON sp.id = d.speciality_id;
