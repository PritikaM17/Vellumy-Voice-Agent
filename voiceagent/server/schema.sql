CREATE TABLE specialities (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                TEXT NOT NULL UNIQUE,
    plain_description   TEXT NOT NULL,
    for_gender          TEXT NOT NULL DEFAULT "any"
                        CHECK (for_gender IN ('any', 'female', 'male'))
);

CREATE TABLE symptoms (
    id        INTEGER GENERATED BY AS IDENTITY PRIMARY KEY,
    snomed_id INTEGER NOT NULL,
    name TEXT NOT NULL UNIQUE,
    embedding BLOB NOT NULL
);

CREATE TABLE symptom_rules (
    id INTEGER GENERATED BY AS IDENTITY PRIMARY KEY,
    speciality_id INTEGER NOT NULL REFERENCES (specialities(id)),
    vote_share FLOAT
);

CREATE TABLE red_flags (
    id INTEGER GENERATED BY IDENTITY PRIMARY KEY,
    phrase TEXT NOT NULL UNIQUE,
    response_message TEXT
)

CREATE TABLE patients (
    id INTEGER GENERATED BY IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT UNIQUE,
    date_of_birth DATE,
    gender TEXT DEFAULT 'any'
            CHECK (gender IN ('any', 'female', 'male'))
);

CREATE TABLE doctors (
    id INTEGER GENERATED BY IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    speciality_id INTEGER REFERENCES (specialities(id)),
    fee INTEGER
);

CREATE TABLE doctor_slots (
    id INTEGER GENERATED BY IDENTITY PRIMARY KEY,
    doctor_id INTEGER UNIQUE REFERENCES (doctors(id)),
    starts_at TIMESTAMPTZ NOT NULL UNIQUE
);

CREATE TABLE symptom_logs (
    id INTEGER GENERATED BY IDENTITY PRIMARY KEY,
    patient_id INTEGER REFERENCES (patients(id)),
    raw_text TEXT NOT NULL,
    phrase TEXT NOT NULL,
    matched_symptom_id INTEGER REFERENCES (symptoms(id)),
    similarity FLOAT,
    suggested_speciality_id INTEGER REFERENCES (specialities(id)),
    reason TEXT,
    is_emergency BOOLEAN NOT NULL DEFAULT FALSE
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

